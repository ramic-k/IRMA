#!/usr/bin/env python3
"""Compute noncubic S(Q,E) and downscatter-side asymmetric S(alpha,|beta|).

This module is IRMA's noncubic inelastic engine: it builds the exact harmonic
one-phonon terms and a sigma_total-scaled incoherent multiphonon background,
then converts them to downscatter-side asymmetric S(alpha,|beta|) for MF7/MT4
export. It is invoked in-process by run_noncubic_sab_inprocess
(inelastic_mode=1/2); a diagnostic CLI (parse_args/main) is also provided.

What this module computes
=========================

It always builds the exact harmonic one-phonon terms:

1. Coherent one-phonon ``S_coh^(1)(Q,E)``
   - with the usual crystal amplitude sum
   - optionally decomposed into diagonal/self and interference pieces
2. Incoherent one-phonon ``S_inc^(1)(Q,E)``
   - the exact self term
3. Incoherent-approximation one-phonon ``S_approx^(1)(Q,E)``
   - the self term scaled with ``sigma_total`` instead of ``sigma_inc``
   - useful as the ``n=1`` partner of the Section 3.10-style multiphonon tail
4. One-phonon total
   - ``S_total^(1) = S_coh^(1) + S_inc^(1)``

It can then add one multiphonon model:

1. ``incoherent_approx``
   - Squires Section 3.10 style approximation for the smooth multiphonon
     background
   - built from the per-atom self kernel and scaled with ``sigma_total``

Relation to Squires
===================

For the exact one-phonon terms:

- coherent ``n=1`` follows the linear ``(UV)`` term from Squires Section 3.7
- incoherent ``n=1`` follows the linear ``(UV0)`` term from Squires Section 3.9
- the ``n=1`` incoherent-approximation branch is not an exact Squires object;
  it is the practical self-term approximation obtained by replacing
  ``sigma_inc`` with ``sigma_total`` in the same self kernel

For the multiphonon part:

- the script builds a per-atom self kernel corresponding to the harmonic
  displacement-correlation object behind ``exp(UV0)``
- the signed-energy kernel is normalized so its unit-``Q`` integral matches the
  thermal-displacement sum rule ``u_hat . U_d . u_hat``
- the higher orders are then generated by the standard harmonic recursion
  ``T_n = (T_1 * T_{n-1}) / n``
- Debye-Waller and scattering cross-section factors are applied after that
  per-atom convolution step
- powder averaging is performed after the fixed-direction convolution, so the
  ordering follows the fixed-``Q`` interpretation of Squires

This module does *not* implement exact coherent multiphonon scattering.
Instead, it adds a practical higher-order background model: exact one-phonon
total plus an incoherent-style multiphonon tail scaled with the total
scattering cross section.

Outputs
=======

The ``.npz`` contains powder-averaged differential ``S(Q,E)`` maps together
with ``alpha``, ``beta_downscatter_abs``, and downscatter-side asymmetric
``S(alpha,|beta|)`` arrays.
The ``sqe_*`` arrays hold the kinematic-factor-free powder scattering intensity
``(sigma / 4 pi) S(Q,E)`` (units ``barn / sr / meV``). This is NOT yet the
measured double-differential cross section: ``d^2 sigma / (dOmega dE') =
(k_f / k_i) (sigma / 4 pi) S(Q,E)`` carries an extra ``k_f / k_i`` factor that
is applied only when projecting onto a specific instrument (see irma.spectra).
The array names carry the ``_barn_per_meV`` suffix for this per-energy
normalization.
The coherent ``n=1`` term is also written as diagonal and interference pieces.
The ``n=1`` incoherent-approximation path is written separately so it can be
combined with the same ``sigma_total`` multiphonon background.

Coherent ``n=1`` powder averaging uses ``directions``: equal-solid-angle
golden-spiral (Fibonacci) directions on a sphere at one radius per ``Q`` bin.
This is the rigorous continuous-direction spherical average and is equivalent
to Euphonic's ``golden`` powder-sampling method.

In particular, the module writes both of the total-cross-section objects
that are useful for OCLIMAX-style workflows:

1. ``sqe_one_phonon_total_plus_incoherent_approx_multiphonon_barn_per_meV``
   - exact coherent ``n=1`` + exact incoherent ``n=1`` + ``sigma_total`` multiphonon
2. ``sqe_incoherent_approx_n1_term_plus_incoherent_approx_multiphonon_barn_per_meV``
   - incoherent-approximation ``n=1`` + the same ``sigma_total`` multiphonon

The matching downscatter-side SAB arrays are written under the same
names with the ``sab_asym_downscatter_`` prefix.

The downscatter-side SAB convention used here is

``S_asym_downscatter(alpha, beta_downscatter_abs) = (4 * pi * kT / sigma_b) * S(Q, E_tr)``

with ``beta_downscatter_abs = E_tr / kT`` and
``alpha = hbar^2 Q^2 / (2 M kT)``.
The same ``sigma_b`` is used for the coherent total, diagonal, and interference
pieces so that the coherent decomposition is preserved in SAB space.
This ``4 * pi`` factor is intentional: it converts the differential
``S(Q,E)`` convention used internally into the standard thermal-scattering-law
normalization.
"""

